export type ProxiedDomain = {
  hostname: string,
  /** Host name of the container, it doesn't need to be known by Docker yet */
  host: string,
  port: number,
};

// The host is in a variable, so Nginx resolves it for the requests instead of while it loads the config
function generateServer({ hostname, host, port }: ProxiedDomain) {
  return `
server {
    listen 80;
    listen [::]:80;
    server_name ${hostname};

    location / {
        set $upstream "${host}:${port}";
        proxy_pass http://$upstream;
    }
}
`;
}

/**
 * Generates the config that is included in the http block of Nginx.
 * - Docker lets its DNS answers be cached for 10 minutes, which is too long for the containers that are replaced.
 * - HTTPS ends at Cloudflare, so the original scheme is always HTTPS.
 * - The default hash buckets are too small for the longest hostnames.
 * - The apps limit the size of their own uploads.
 */
export function generateProxyConfig(domains: ProxiedDomain[]) {
  return `# Generated by Buttler, changes will be lost
resolver 127.0.0.11 valid=5s ipv6=off;
resolver_timeout 5s;
server_names_hash_bucket_size 512;
client_max_body_size 0;

map $http_upgrade $connection_upgrade {
    default upgrade;
    "" close;
}

proxy_http_version 1.1;
proxy_set_header Host $host;
proxy_set_header X-Forwarded-Host $host;
proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
proxy_set_header X-Forwarded-Proto https;
proxy_set_header Upgrade $http_upgrade;
proxy_set_header Connection $connection_upgrade;

server {
    listen 80 default_server;
    listen [::]:80 default_server;
    server_name _;

    location /healthz {
        access_log off;
        default_type text/plain;
        return 200 "healthy\\n";
    }

    location / {
        return 404;
    }
}
${domains.map(generateServer).join("")}`;
}

export function generateNginxConfig(_appHostName?: string) {
  return "events {}\n\nhttp {}\n";
}
